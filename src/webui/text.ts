export type PanelText = typeof zh;

export function panelText(language: string): PanelText {
  return language === 'zh' || language === 'zh-Hant' ? zh : en;
}

/** 分钟数写成「1 小时 5 分钟」/「1 h 5 min」。 */
export function hours(min: number, language: string): string {
  const h = Math.floor(min / 60), m = min % 60;
  if (language === 'zh' || language === 'zh-Hant') return h ? `${h} 小时 ${m} 分钟` : `${m} 分钟`;
  return h ? `${h} h ${m} min` : `${m} min`;
}
